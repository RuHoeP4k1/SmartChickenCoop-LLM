"""
human_ranking.py — Human pairwise preference study

Walks a rater through blinded A/B comparisons of LLM answers generated by
different prompt variants. Results are aggregated into win rates and an ELO
ranking so prompt variants can be compared on human preference rather than
automated metrics alone.

Workflow:
  1. Run evaluate_prompt_variants.py --export-pairs
     → generates evaluation/results/prompt_pairs.json
  2. Run this script to rate comparisons:
     python evaluation/human_ranking.py
  3. View current standings at any time:
     python evaluation/human_ranking.py --results

Pairs are saved incrementally after each rating so you can stop and resume.
Multiple raters can each create their own output file with --rater-id.

Usage:
    python evaluation/human_ranking.py
    python evaluation/human_ranking.py --rater-id romeo
    python evaluation/human_ranking.py --results
    python evaluation/human_ranking.py --results --input results/human_rankings_romeo.json
    python evaluation/human_ranking.py --n-pairs 10    # rate only 10 pairs
"""

import os
import sys
import json
import math
import argparse
from datetime import datetime
from typing import Dict, List, Optional

_HERE = os.path.dirname(os.path.abspath(__file__))


# =============================================================================
# ELO CALCULATION
# =============================================================================

def compute_elo(
    results: List[Dict],
    k: int = 32,
    initial: int = 1000,
) -> Dict[str, float]:
    """
    Compute ELO ratings from pairwise preference results.

    Args:
        results: List of rated pairs (each has answer_a.variant, answer_b.variant, winner)
        k: ELO K-factor (sensitivity to each match; 32 is standard for chess beginners)
        initial: Starting ELO for all variants

    Returns:
        Dict mapping variant name → ELO rating
    """
    elo: Dict[str, float] = {}

    for pair in results:
        winner = pair.get("winner")
        if winner not in ("a", "b", "tie"):
            continue

        v_a = pair["answer_a"]["variant"]
        v_b = pair["answer_b"]["variant"]

        if v_a not in elo:
            elo[v_a] = initial
        if v_b not in elo:
            elo[v_b] = initial

        r_a, r_b = elo[v_a], elo[v_b]
        expected_a = 1.0 / (1.0 + 10 ** ((r_b - r_a) / 400.0))
        expected_b = 1.0 - expected_a

        if winner == "a":
            score_a, score_b = 1.0, 0.0
        elif winner == "b":
            score_a, score_b = 0.0, 1.0
        else:  # tie
            score_a, score_b = 0.5, 0.5

        elo[v_a] = r_a + k * (score_a - expected_a)
        elo[v_b] = r_b + k * (score_b - expected_b)

    return elo


def compute_win_rates(results: List[Dict]) -> Dict[str, Dict]:
    """
    Compute raw win / loss / tie counts per variant.

    Returns:
        {variant: {"wins": int, "losses": int, "ties": int, "total": int, "win_rate": float}}
    """
    stats: Dict[str, Dict] = {}

    def _get(v):
        if v not in stats:
            stats[v] = {"wins": 0, "losses": 0, "ties": 0, "total": 0}
        return stats[v]

    for pair in results:
        winner = pair.get("winner")
        if winner not in ("a", "b", "tie"):
            continue

        v_a = pair["answer_a"]["variant"]
        v_b = pair["answer_b"]["variant"]
        s_a = _get(v_a)
        s_b = _get(v_b)

        s_a["total"] += 1
        s_b["total"] += 1

        if winner == "a":
            s_a["wins"] += 1
            s_b["losses"] += 1
        elif winner == "b":
            s_b["wins"] += 1
            s_a["losses"] += 1
        else:
            s_a["ties"] += 1
            s_b["ties"] += 1

    for v, s in stats.items():
        s["win_rate"] = (s["wins"] + 0.5 * s["ties"]) / s["total"] if s["total"] > 0 else 0.0

    return stats


# =============================================================================
# DISPLAY
# =============================================================================

def _wrap(text: str, width: int = 90, indent: int = 2) -> str:
    """Wrap long text to terminal width."""
    prefix = " " * indent
    words = text.split()
    lines, current = [], ""
    for word in words:
        if current and len(current) + len(word) + 1 > width - indent:
            lines.append(prefix + current)
            current = word
        else:
            current = (current + " " + word).strip()
    if current:
        lines.append(prefix + current)
    return "\n".join(lines)


def display_pair(pair: Dict, pair_index: int, total: int) -> None:
    """Display a single comparison pair for the rater."""
    print("\n" + "=" * 90)
    print(f"  COMPARISON {pair_index + 1} of {total}  —  category: {pair.get('category', '?')}")
    print("=" * 90)
    print(f"\n  QUESTION:\n{_wrap(pair['question'])}\n")

    print("─" * 90)
    print("  ANSWER A:")
    print("─" * 90)
    print(_wrap(pair["answer_a"]["text"], width=90, indent=2))

    print("\n" + "─" * 90)
    print("  ANSWER B:")
    print("─" * 90)
    print(_wrap(pair["answer_b"]["text"], width=90, indent=2))
    print()


def display_results(results: List[Dict]) -> None:
    """Print current win-rate table and ELO ranking."""
    rated = [r for r in results if r.get("winner") in ("a", "b", "tie")]
    if not rated:
        print("No rated pairs yet.")
        return

    win_rates = compute_win_rates(rated)
    elo_scores = compute_elo(rated)

    all_variants = sorted(
        set(list(win_rates.keys()) + list(elo_scores.keys()))
    )

    print("\n" + "=" * 70)
    print(f"HUMAN RANKING RESULTS  ({len(rated)} rated pairs)")
    print("=" * 70)
    print(f"\n{'Variant':<16} {'ELO':>6} {'Win%':>6} {'Wins':>5} {'Losses':>7} {'Ties':>5} {'Total':>6}")
    print("─" * 60)

    ranked = sorted(all_variants, key=lambda v: elo_scores.get(v, 1000), reverse=True)
    for v in ranked:
        s = win_rates.get(v, {"wins": 0, "losses": 0, "ties": 0, "total": 0, "win_rate": 0.0})
        elo = elo_scores.get(v, 1000)
        print(f"{v:<16} {elo:>6.0f} {100*s['win_rate']:>5.1f}%"
              f" {s['wins']:>5} {s['losses']:>7} {s['ties']:>5} {s['total']:>6}")

    # Per-category breakdown
    categories = sorted(set(r.get("category", "?") for r in rated))
    if len(categories) > 1:
        print("\nPer-category win rates:")
        for cat in categories:
            cat_rated = [r for r in rated if r.get("category") == cat]
            cat_wins = compute_win_rates(cat_rated)
            ranked_cat = sorted(cat_wins.keys(), key=lambda v: cat_wins[v]["win_rate"], reverse=True)
            rates = "  ".join(
                f"{v}: {100*cat_wins[v]['win_rate']:.0f}%" for v in ranked_cat
            )
            print(f"  {cat:<12} {rates}")


# =============================================================================
# INTERACTIVE RATING LOOP
# =============================================================================

def rate_pairs(
    pairs_file: str,
    output_file: str,
    n_pairs: Optional[int] = None,
    rater_id: str = "default",
) -> None:
    """Walk the rater through unrated pairs and save results."""
    if not os.path.exists(pairs_file):
        print(f"Error: pairs file not found: {pairs_file}")
        print("Run evaluate_prompt_variants.py --export-pairs first.")
        sys.exit(1)

    with open(pairs_file) as f:
        all_pairs: List[Dict] = json.load(f)

    # Load existing ratings (resume support)
    if os.path.exists(output_file):
        with open(output_file) as f:
            rated: List[Dict] = json.load(f)
        rated_ids = {r["pair_id"] for r in rated}
        print(f"Resuming: {len(rated_ids)} pairs already rated.")
    else:
        rated = []
        rated_ids = set()

    # Filter to unrated pairs only
    unrated = [p for p in all_pairs if p["pair_id"] not in rated_ids]
    if n_pairs:
        unrated = unrated[:n_pairs]

    if not unrated:
        print("All pairs have been rated. Run --results to see standings.")
        return

    total_session = len(unrated)
    print(f"\n{total_session} pairs to rate this session.")
    print("For each pair: enter  A  (prefer A),  B  (prefer B),  T  (tie),  S  (skip),  Q  (quit)")

    for i, pair in enumerate(unrated):
        display_pair(pair, i, total_session)

        while True:
            raw = input("  Your choice [A/B/T/S/Q]: ").strip().upper()
            if raw in ("A", "B", "T", "S", "Q"):
                break
            print("  Please enter A, B, T, S, or Q.")

        if raw == "Q":
            print("\nSession ended.")
            break

        if raw == "S":
            print("  Skipped.")
            continue

        winner_map = {"A": "a", "B": "b", "T": "tie"}
        result = {
            **pair,
            "winner": winner_map[raw],
            "rater_id": rater_id,
            "rated_at": datetime.utcnow().isoformat(),
        }
        rated.append(result)
        rated_ids.add(pair["pair_id"])

        # Save incrementally so a crash doesn't lose progress
        with open(output_file, "w") as f:
            json.dump(rated, f, indent=2)

    print(f"\n{len(rated)} total ratings saved to: {output_file}")
    display_results(rated)


# =============================================================================
# ENTRY POINT
# =============================================================================

if __name__ == "__main__":
    RESULTS_DIR = os.path.join(_HERE, "results")
    DEFAULT_PAIRS  = os.path.join(RESULTS_DIR, "prompt_pairs.json")
    DEFAULT_OUTPUT = os.path.join(RESULTS_DIR, "human_rankings.json")

    parser = argparse.ArgumentParser(description="Human pairwise preference ranking")
    parser.add_argument("--input",  default=DEFAULT_PAIRS,
                        help="Path to prompt_pairs.json (from evaluate_prompt_variants.py)")
    parser.add_argument("--output", default=DEFAULT_OUTPUT,
                        help="Where to save/load ratings (default: results/human_rankings.json)")
    parser.add_argument("--rater-id", default="default",
                        help="Your name/ID (used when multiple raters collaborate)")
    parser.add_argument("--n-pairs", type=int, default=None,
                        help="Rate at most N pairs in this session")
    parser.add_argument("--results", action="store_true",
                        help="Just show current standings and exit")
    args = parser.parse_args()

    # Override output file name when a rater-id is given
    if args.rater_id != "default" and args.output == DEFAULT_OUTPUT:
        args.output = os.path.join(RESULTS_DIR, f"human_rankings_{args.rater_id}.json")

    os.makedirs(RESULTS_DIR, exist_ok=True)

    if args.results:
        if not os.path.exists(args.output):
            print(f"No ratings file found at: {args.output}")
        else:
            with open(args.output) as f:
                rated = json.load(f)
            display_results(rated)
    else:
        rate_pairs(
            pairs_file=args.input,
            output_file=args.output,
            n_pairs=args.n_pairs,
            rater_id=args.rater_id,
        )
